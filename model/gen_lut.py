"""
gen_lut.py - generates rtl/exp2_lut.v (a synthesizable case-statement ROM)
from the same LUT used by the bit-exact Python model.

Run from the repo root:  python model/gen_lut.py
"""
import os
from fixed_model import LUT, LUT_BITS

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
path = os.path.join(root, "rtl", "exp2_lut.v")
n = 1 << LUT_BITS
with open(path, "w") as f:
    f.write("// AUTO-GENERATED by model/gen_lut.py -- do not edit by hand.\n")
    f.write(f"// exp2_lut: data = round(65536 * 2^(-(idx+0.5)/{n}))  (Q0.16, mid-point of each bin)\n")
    f.write("`timescale 1ns/1ps\n")
    f.write(f"module exp2_lut (\n    input  wire [{LUT_BITS-1}:0] idx,\n    output reg  [15:0] data\n);\n")
    f.write("    always @(*) begin\n        case (idx)\n")
    for i, v in enumerate(LUT):
        f.write(f"            {LUT_BITS}'d{i:<2}: data = 16'd{v};\n")
    f.write("            default: data = 16'd0;\n        endcase\n    end\nendmodule\n")
print("wrote", path)
